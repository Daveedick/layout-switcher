import AppKit
import Foundation

/// A bounded, ownership-checked transaction for temporarily replacing a pasteboard.
/// It never dispatches keyboard events; callers own focus checks and Cmd+V delivery.
final class ClipboardReplacement {
    private struct SnapshotItem {
        let representations: [(NSPasteboard.PasteboardType, Data)]

        func makePasteboardItem() -> NSPasteboardItem {
            let item = NSPasteboardItem()
            for (type, data) in representations { item.setData(data, forType: type) }
            return item
        }
    }

    private enum RestoreOutcome { case restored, ownershipLost, retryable }

    private static let maxSnapshotBytes = 64 * 1024 * 1024
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autogeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static var activeTransaction: ClipboardReplacement?

    private let pasteboard: NSPasteboard
    private let snapshot: [SnapshotItem]
    private let markerType: NSPasteboard.PasteboardType
    private let markerData: Data
    private var replacementChangeCount: Int?
    private var clearedChangeCount: Int?
    private var finishScheduled = false
    private var retryScheduled = false
    private var restoreAttempts = 0
    private let maximumRestoreAttempts = 4

    private init(pasteboard: NSPasteboard, snapshot: [SnapshotItem], markerType: NSPasteboard.PasteboardType,
                 markerData: Data) {
        self.pasteboard = pasteboard
        self.snapshot = snapshot
        self.markerType = markerType
        self.markerData = markerData
    }

    /// Snapshots every pasteboard flavor, then writes replacement text as one marked item.
    /// All pasteboard reads and writes run synchronously on the main thread.
    static func prepare(text: String, pasteboard requestedPasteboard: NSPasteboard? = nil) -> ClipboardReplacement? {
        guard text.utf8.count <= maxSnapshotBytes else { return nil }
        return onMain {
            let pasteboard = requestedPasteboard ?? NSPasteboard.general
            if let previous = activeTransaction {
                // A lost owner means the user or another app replaced the clipboard; release the
                // stale snapshot and allow a new transaction. An owned transaction blocks overlap.
                if !previous.ownsReplacement() && !previous.ownsClearedPasteboard() {
                    activeTransaction = nil
                } else {
                    return nil
                }
            }
            guard let originalCount = snapshotChangeCount(pasteboard),
                  let snapshot = makeSnapshot(pasteboard, expectedChangeCount: originalCount),
                  pasteboard.changeCount == originalCount else { return nil }

            let uuid = UUID().uuidString.lowercased()
            let markerType = NSPasteboard.PasteboardType("org.codex.layout-switcher.replacement.\(uuid)")
            let markerData = Data(uuid.utf8)
            let transaction = ClipboardReplacement(pasteboard: pasteboard, snapshot: snapshot,
                                                   markerType: markerType, markerData: markerData)
            pasteboard.clearContents()
            transaction.clearedChangeCount = pasteboard.changeCount

            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            item.setData(markerData, forType: markerType)
            // Clipboard-manager hints are advisory. The private UUID flavor is the ownership check.
            item.setData(Data(), forType: transientType)
            item.setData(Data(), forType: autogeneratedType)
            let writeSucceeded = pasteboard.writeObjects([item])
            transaction.replacementChangeCount = pasteboard.changeCount
            if writeSucceeded, transaction.ownsReplacement() {
                activeTransaction = transaction
                return transaction
            }

            // A failed write may have left the pasteboard empty or partially populated. Restore
            // only while the unchanged count and empty state prove our clear operation still owns it.
            if transaction.ownsReplacement() || transaction.ownsClearedPasteboard() {
                activeTransaction = transaction
                transaction.restoreAndReleaseIfOwned()
            }
            return nil
        }
    }

    /// Restore immediately after the caller confirms the target consumed the replacement.
    /// If unconfirmed, retain the transaction briefly for delayed paste/readback completion.
    @discardableResult
    func finish(confirmed: Bool) -> Bool {
        if confirmed {
            if Thread.isMainThread {
                finishScheduled = false
                return restoreAndReleaseIfOwned()
            } else {
                return restoreToCompletion(maxRetries: 3)
            }
        }

        let shouldWait = Self.onMain { () -> Bool in
            guard Self.activeTransaction === self else { return false }
            if !finishScheduled {
                finishScheduled = true
                DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(850)) { [self] in
                    guard Self.activeTransaction === self else { return }
                    finishScheduled = false
                    restoreAndReleaseIfOwned()
                }
            }
            return true
        }
        // The AX worker must not return and replay held user events until its clipboard is restored.
        if !shouldWait { return true }
        if Thread.isMainThread { return true }
        return restoreToCompletion(maxRetries: 3, waitBeforeFirstAttempt: 0.85)
    }

    /// Call only before dispatching Cmd+V. It restores the original pasteboard now if still owned.
    @discardableResult
    func cancelBeforeDispatch() -> Bool {
        if Thread.isMainThread {
            guard Self.activeTransaction === self else { return true }
            finishScheduled = false
            return restoreAndReleaseIfOwned()
        } else {
            return restoreToCompletion(maxRetries: 3)
        }
    }

    /// Flushes a pending owned transaction during orderly application termination.
    static func flushIfOwned() {
        onMain {
            guard let activeTransaction else { return }
            activeTransaction.finishScheduled = false
            activeTransaction.retryScheduled = false
            activeTransaction.restoreAttempts = 0
            for _ in 0..<activeTransaction.maximumRestoreAttempts {
                switch activeTransaction.restoreIfOwned() {
                case .restored, .ownershipLost:
                    ClipboardReplacement.activeTransaction = nil
                    return
                case .retryable:
                    continue
                }
            }
        }
    }

    /// True when a queued ordinary paste may be replayed without this helper still owning the clipboard.
    static func isReadyForInputReplay() -> Bool {
        onMain {
            guard let activeTransaction else { return true }
            guard activeTransaction.ownsReplacement() || activeTransaction.ownsClearedPasteboard() else {
                ClipboardReplacement.activeTransaction = nil
                return true
            }
            return false
        }
    }

    /// Entry point for the explicit menu action. It only converts one copied text item.
    static func transformCopiedText(on pasteboard: NSPasteboard, transform: (String) -> String?) -> Bool {
        onMain {
            guard isReadyForInputReplay() else { return false }
            let initialCount = pasteboard.changeCount
            let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
            guard let items = pasteboard.pasteboardItems, items.count == 1, let item = items.first,
                  !item.types.contains(.fileURL), !item.types.contains(concealed),
                  let original = item.string(forType: .string), original.utf8.count <= 256 * 1024,
                  let converted = transform(original), converted != original else { return false }
            let replacement = NSPasteboardItem()
            guard replacement.setString(converted, forType: .string),
                  pasteboard.changeCount == initialCount else { return false }
            pasteboard.clearContents()
            return pasteboard.writeObjects([replacement])
        }
    }

    /// Confirms that this prepared transaction still owns the replacement immediately before dispatch.
    func isPreparedReplacementCurrent() -> Bool {
        Self.onMain {
            Self.activeTransaction === self && ownsReplacement()
        }
    }

    private func restoreAndReleaseIfOwned() -> Bool {
        switch restoreIfOwned() {
        case .restored, .ownershipLost:
            if Self.activeTransaction === self { Self.activeTransaction = nil }
            return true
        case .retryable:
            scheduleRetry()
            return false
        }
    }

    private func restoreToCompletion(maxRetries: Int, waitBeforeFirstAttempt: TimeInterval = 0) -> Bool {
        if waitBeforeFirstAttempt > 0 { Thread.sleep(forTimeInterval: waitBeforeFirstAttempt) }
        for attempt in 0...maxRetries {
            let completed = Self.onMain { () -> Bool in
                guard Self.activeTransaction === self else { return true }
                finishScheduled = false
                retryScheduled = false
                switch restoreIfOwned() {
                case .restored, .ownershipLost:
                    Self.activeTransaction = nil
                    return true
                case .retryable:
                    return false
                }
            }
            if completed { return true }
            if attempt < maxRetries { Thread.sleep(forTimeInterval: 0.1) }
        }
        return false
    }

    private func restoreIfOwned() -> RestoreOutcome {
        guard ownsReplacement() || ownsClearedPasteboard() else { return .ownershipLost }
        guard restoreAttempts < maximumRestoreAttempts else { return .retryable }
        restoreAttempts += 1

        pasteboard.clearContents()
        let clearedCount = pasteboard.changeCount
        clearedChangeCount = clearedCount
        replacementChangeCount = nil
        guard !snapshot.isEmpty else { return .restored }

        let originalItems = snapshot.map { $0.makePasteboardItem() }
        if pasteboard.writeObjects(originalItems) { return .restored }

        // Retry only if the failed restore left our clear operation untouched and empty.
        guard pasteboard.changeCount == clearedCount,
              pasteboard.pasteboardItems?.isEmpty ?? true else { return .ownershipLost }
        return .retryable
    }

    private func scheduleRetry() {
        guard !retryScheduled, restoreAttempts < maximumRestoreAttempts else { return }
        retryScheduled = true
        DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(200)) { [self] in
            guard Self.activeTransaction === self else { return }
            retryScheduled = false
            restoreAndReleaseIfOwned()
        }
    }

    private func ownsReplacement() -> Bool {
        guard let replacementChangeCount,
              pasteboard.changeCount == replacementChangeCount,
              let items = pasteboard.pasteboardItems else { return false }
        return items.contains { $0.data(forType: markerType) == markerData }
    }

    private func ownsClearedPasteboard() -> Bool {
        guard let clearedChangeCount, pasteboard.changeCount == clearedChangeCount else { return false }
        return pasteboard.pasteboardItems?.isEmpty ?? true
    }

    private static func snapshotChangeCount(_ pasteboard: NSPasteboard) -> Int? {
        pasteboard.changeCount
    }

    private static func makeSnapshot(_ pasteboard: NSPasteboard,
                                     expectedChangeCount: Int) -> [SnapshotItem]? {
        guard pasteboard.changeCount == expectedChangeCount else { return nil }
        guard let items = pasteboard.pasteboardItems else {
            return (pasteboard.types?.isEmpty ?? true) ? [] : nil
        }

        var totalBytes = 0
        var snapshot: [SnapshotItem] = []
        snapshot.reserveCapacity(items.count)
        for item in items {
            let types = item.types
            guard !types.isEmpty else { return nil }
            var representations: [(NSPasteboard.PasteboardType, Data)] = []
            representations.reserveCapacity(types.count)
            for type in types {
                guard let data = item.data(forType: type) else { return nil }
                let (newTotal, overflow) = totalBytes.addingReportingOverflow(data.count)
                guard !overflow, newTotal <= maxSnapshotBytes else { return nil }
                totalBytes = newTotal
                representations.append((type, Data(data)))
            }
            snapshot.append(SnapshotItem(representations: representations))
        }
        guard pasteboard.changeCount == expectedChangeCount else { return nil }
        return snapshot
    }

    private static func onMain<T>(_ operation: () -> T) -> T {
        if Thread.isMainThread { return operation() }
        return DispatchQueue.main.sync(execute: operation)
    }
}
